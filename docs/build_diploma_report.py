def add_content_page(doc: Document, spec: dict) -> None:
    add_heading(doc, spec["title"], level=1, centered=spec.get("center", False))
    if spec.get("subtitle"):
        add_heading(doc, spec["subtitle"], level=2)
    for paragraph in spec.get("paragraphs", []):
        add_text(doc, paragraph)
    if spec.get("flow"):
        title, items = spec["flow"]
        add_flow(doc, title, items)
    if spec.get("table"):
        title, headers, rows = spec["table"]
        add_table(doc, title, headers, rows)


def validate_source_text() -> None:
    fragments = []
    for spec in PAGES:
        fragments.extend([spec.get("title", ""), spec.get("subtitle", "")])
        fragments.extend(spec.get("paragraphs", []))
        if spec.get("flow"):
            fragments.append(spec["flow"][0])
            fragments.extend(spec["flow"][1])
        if spec.get("table"):
            fragments.append(spec["table"][0])
            fragments.extend(spec["table"][1])
            for row in spec["table"][2]:
                fragments.extend(row)
    combined = "\n".join(fragments)
    forbidden = [item for item in ("ё", "Ё", "—", "–", "‑", "...") if item in combined]
    if forbidden:
        raise ValueError(f"Forbidden text patterns found: {forbidden}")


